/**
 * `frontmcp skills export --from-entry --provider claude,codex` writes a server's own `@Skill` entries to each
 * agent's skills folder from one source, and `--check` fails once a copy drifts from it.
 */
import * as os from 'node:os';
import * as path from 'node:path';

import { ensureDir, mkdtemp, readFile, rm, writeFile } from '@frontmcp/utils';

import { getFixtureDir, runFrontmcpCli } from './helpers/exec-cli';

const SCRATCH_ROOT = path.resolve(__dirname, '..');

function exportSkills(cwd: string, ...extra: string[]) {
  return runFrontmcpCli(
    ['skills', 'export', '--from-entry', 'src/main.ts', '--all', '--provider', 'claude,codex', ...extra],
    undefined,
    cwd,
    90_000,
  );
}

describe('frontmcp skills export --from-entry', () => {
  let outDir: string;

  beforeAll(async () => {
    outDir = await mkdtemp(path.join(os.tmpdir(), 'frontmcp-skills-export-'));
  });

  afterAll(async () => {
    await rm(outDir, { recursive: true, force: true });
  });

  it("writes every @Skill of the fixture to both providers' folders, with its tools generated from the server", async () => {
    const { exitCode, stderr } = exportSkills(getFixtureDir(), '--out', outDir);
    expect({ exitCode, stderr }).toEqual({ exitCode: 0, stderr: '' });

    for (const provider of ['.claude', '.codex']) {
      const greeting = await readFile(path.join(outDir, provider, 'skills', 'greeting-helper', 'SKILL.md'));
      expect(greeting).toContain('description: A helper skill for greeting users');
      expect(greeting).toMatch(
        /<!-- generated by frontmcp skills export from src\/main\.ts \(source hash [0-9a-f]{64}\)/,
      );
      expect(greeting).toContain('## Greeting Guide');
      expect(greeting).toContain('## Tools\n\n- `greet`: Greet a user by name');
      const math = await readFile(path.join(outDir, provider, 'skills', 'math-helper', 'SKILL.md'));
      expect(math).toContain('## Math Helper');
    }
  });

  it('passes --check on the fresh copies and fails it on a copy edited by hand', async () => {
    const clean = exportSkills(getFixtureDir(), '--out', outDir, '--check');
    expect(clean.exitCode).toBe(0);
    expect(clean.stdout).toContain('2 skill(s) in claude, codex match src/main.ts.');

    const copy = path.join(outDir, '.codex', 'skills', 'math-helper', 'SKILL.md');
    await writeFile(copy, (await readFile(copy)).replace('## Math Helper', '## Math Helper (edited)'));
    const drifted = exportSkills(getFixtureDir(), '--out', outDir, '--check');
    expect(drifted.exitCode).toBe(1);
    expect(drifted.stderr).toContain('.codex/skills/math-helper: modified: SKILL.md differs from the source');
  });

  describe('after the source skill changes', () => {
    let projectDir: string;

    beforeAll(async () => {
      projectDir = await mkdtemp(path.join(SCRATCH_ROOT, '.scratch-skills-export-'));
      await ensureDir(path.join(projectDir, 'src'));
      await writeFile(path.join(projectDir, 'src', 'runbook.md'), '# Deploy runbook\n\nShip on Tuesdays.\n');
      await writeFile(
        path.join(projectDir, 'src', 'main.ts'),
        `import 'reflect-metadata';
import { App, FrontMcp, LogLevel, Skill } from '@frontmcp/sdk';

@Skill({ name: 'deploy-runbook', description: 'How we deploy', instructions: { file: './runbook.md' } })
class DeployRunbookSkill {}

@App({ name: 'ops', skills: [DeployRunbookSkill] })
class OpsApp {}

@FrontMcp({ info: { name: 'Export Demo', version: '1.0.0' }, apps: [OpsApp], logging: { level: LogLevel.Off } })
export default class Server {}
`,
      );
    });

    afterAll(async () => {
      await rm(projectDir, { recursive: true, force: true });
    });

    it('fails --check until the skills are exported again', async () => {
      expect(exportSkills(projectDir).exitCode).toBe(0);
      expect(await readFile(path.join(projectDir, '.claude', 'skills', 'deploy-runbook', 'SKILL.md'))).toContain(
        'Ship on Tuesdays.',
      );
      expect(exportSkills(projectDir, '--check').exitCode).toBe(0);

      await writeFile(path.join(projectDir, 'src', 'runbook.md'), '# Deploy runbook\n\nShip on Thursdays.\n');
      const stale = exportSkills(projectDir, '--check');
      expect(stale.exitCode).toBe(1);
      expect(stale.stderr).toContain(
        '.claude/skills/deploy-runbook: stale: the skill changed in the source since this copy was exported',
      );
      expect(stale.stderr).toContain('.codex/skills/deploy-runbook: stale');

      expect(exportSkills(projectDir).exitCode).toBe(0);
      expect(exportSkills(projectDir, '--check').exitCode).toBe(0);
      expect(await readFile(path.join(projectDir, '.codex', 'skills', 'deploy-runbook', 'SKILL.md'))).toContain(
        'Ship on Thursdays.',
      );
    }, 300_000);
  });
});
