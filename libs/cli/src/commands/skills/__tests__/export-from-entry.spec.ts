import { symlinkSync } from 'fs';
import * as os from 'os';
import * as path from 'path';

import { ensureDir, fileExists, lstat, mkdtemp, readFile, rm, writeFile } from '@frontmcp/utils';

import type { ExtractedSchema } from '../../build/exec/cli-runtime/schema-extractor';
import { exportSkillsFromEntry } from '../export-from-entry';

const mockExtract = jest.fn();
jest.mock('../from-entry', () => ({
  extractProjectSchema: (...args: unknown[]) => mockExtract(...args),
}));

let project: string;

function schema(overrides: { hash?: string; greetingBody?: string; skills?: unknown[] } = {}): ExtractedSchema {
  return {
    tools: [],
    resources: [],
    resourceTemplates: [],
    prompts: [],
    jobs: [],
    capabilities: { skills: true, jobs: false, workflows: false },
    skillAssets: [
      {
        skillName: 'greeting',
        instructionFile: path.join(project, 'src', 'greeting.md'),
        resourceDirs: { references: path.join(project, 'src', 'refs') },
      },
      { skillName: 'inline', instructionContent: '---\nname: inline\ndescription: Own frontmatter\n---\nInline body.' },
    ],
    manifest: {
      manifestVersion: 1,
      tools: [{ name: 'greet', description: 'Greet someone\nby name' }],
      skills: overrides.skills ?? [
        {
          name: 'greeting',
          description: 'Greet users',
          tags: ['hello'],
          tools: [{ name: 'greet' }, { name: 'wave', purpose: 'Wave back' }, { name: 'nod' }],
          hash: overrides.hash ?? 'a1',
        },
        { name: 'inline', description: 'Own frontmatter', tools: [], hash: 'b2' },
      ],
    },
  } as ExtractedSchema;
}

async function run(options: Partial<Parameters<typeof exportSkillsFromEntry>[0]> = {}): Promise<number> {
  process.exitCode = undefined;
  await exportSkillsFromEntry({ entry: 'src/main.ts', providers: ['claude', 'codex'], all: true, ...options });
  const code = process.exitCode ?? 0;
  process.exitCode = undefined;
  return code;
}

const errors = () => (console.error as jest.Mock).mock.calls.map((call) => String(call[0])).join('\n');

beforeEach(async () => {
  project = await mkdtemp(path.join(os.tmpdir(), 'frontmcp-export-from-entry-'));
  await ensureDir(path.join(project, 'src', 'refs'));
  await writeFile(path.join(project, 'src', 'main.ts'), 'export default {};');
  await writeFile(path.join(project, 'src', 'greeting.md'), '## Greeting\n\nSay hello.\n');
  await writeFile(path.join(project, 'src', 'refs', 'tone.md'), 'Be kind.');
  mockExtract.mockReset();
  mockExtract.mockResolvedValue(schema());
  jest.spyOn(process, 'cwd').mockReturnValue(project);
  jest.spyOn(process, 'exit').mockImplementation(((code?: number) => {
    throw new Error(`process.exit(${code})`);
  }) as never);
  jest.spyOn(console, 'log').mockImplementation(() => undefined);
  jest.spyOn(console, 'error').mockImplementation(() => undefined);
});

afterEach(async () => {
  jest.restoreAllMocks();
  await rm(project, { recursive: true, force: true });
});

describe('frontmcp skills export --from-entry', () => {
  it("writes each skill to every provider's folder with its source marker, tools and resources", async () => {
    expect(await run()).toBe(0);

    for (const dir of ['.claude/skills', '.codex/skills']) {
      const skillMd = await readFile(path.join(project, dir, 'greeting', 'SKILL.md'));
      expect(skillMd).toBe(
        [
          '---',
          'name: greeting',
          'description: Greet users',
          'tags: [hello]',
          '---',
          '<!-- generated by frontmcp skills export from src/main.ts (source hash a1); edit the source and export again -->',
          '',
          '## Greeting',
          '',
          'Say hello.',
          '',
          '## Tools',
          '',
          '- `greet`: Greet someone',
          '- `wave`: Wave back',
          '- `nod`',
          '',
        ].join('\n'),
      );
      expect(await readFile(path.join(project, dir, 'greeting', 'references', 'tone.md'))).toBe('Be kind.');
    }
    expect(mockExtract).toHaveBeenCalledWith({ entry: path.join(project, 'src', 'main.ts'), cwd: project });
  });

  it('keeps a body that has its own frontmatter, with the marker after it', async () => {
    await run({ providers: ['codex'] });

    expect(await readFile(path.join(project, '.codex/skills/inline/SKILL.md'))).toBe(
      '---\nname: inline\ndescription: Own frontmatter\n---\n' +
        '<!-- generated by frontmcp skills export from src/main.ts (source hash b2); edit the source and export again -->\n\n' +
        'Inline body.\n',
    );
  });

  it('passes --check right after an export', async () => {
    await run();

    expect(await run({ check: true })).toBe(0);
    expect(console.log).toHaveBeenCalledWith(expect.stringContaining('2 skill(s) in claude, codex match src/main.ts'));
  });

  it('fails --check on a copy edited by hand, a missing copy, and a stale one', async () => {
    await run();
    await writeFile(path.join(project, '.claude/skills/greeting/SKILL.md'), 'edited');
    await rm(path.join(project, '.codex/skills/inline'), { recursive: true, force: true });

    expect(await run({ check: true })).toBe(1);
    expect(errors()).toContain(
      `drift: ${path.join('.claude', 'skills', 'greeting')}: not written by frontmcp skills export`,
    );
    expect(errors()).toContain(`drift: ${path.join('.codex', 'skills', 'inline')}: missing`);

    await rm(path.join(project, '.claude/skills/greeting'), { recursive: true, force: true });
    await run();
    mockExtract.mockResolvedValue(schema({ hash: 'c3' }));
    expect(await run({ check: true, providers: ['claude'] })).toBe(1);
    expect(errors()).toContain('stale: the skill changed in the source since this copy was exported');
  });

  it('fails --check on a body or a resource that differs from the source', async () => {
    await run({ providers: ['claude'] });
    const skillMdPath = path.join(project, '.claude/skills/greeting/SKILL.md');
    await writeFile(skillMdPath, (await readFile(skillMdPath)).replace('Say hello.', 'Say hi.'));
    expect(await run({ check: true, providers: ['claude'] })).toBe(1);
    expect(errors()).toContain('modified: SKILL.md differs from the source');

    await run({ providers: ['claude'] });
    await writeFile(path.join(project, '.claude/skills/greeting/references/extra.md'), 'not in the source');
    expect(await run({ check: true, providers: ['claude'] })).toBe(1);
    expect(errors()).toContain('modified: references/extra.md is not in the source');

    await run({ providers: ['claude'] });
    await rm(path.join(project, '.claude/skills/greeting/references/tone.md'));
    expect(await run({ check: true, providers: ['claude'] })).toBe(1);
    expect(errors()).toContain('modified: references/tone.md is missing');
  });

  it('removes, or with --check reports, a copy whose skill left the source', async () => {
    await run({ providers: ['claude'] });
    await ensureDir(path.join(project, '.claude/skills/hand-made'));
    await writeFile(path.join(project, '.claude/skills/hand-made/SKILL.md'), 'not exported');
    mockExtract.mockResolvedValue(schema({ skills: [{ name: 'inline', description: 'Own', tools: [], hash: 'b2' }] }));

    expect(await run({ check: true, providers: ['claude'] })).toBe(1);
    expect(errors()).toContain(`drift: ${path.join('.claude', 'skills', 'greeting')}: removed from the source`);

    expect(await run({ providers: ['claude'] })).toBe(0);
    expect(await fileExists(path.join(project, '.claude/skills/greeting'))).toBe(false);
    expect(await fileExists(path.join(project, '.claude/skills/hand-made/SKILL.md'))).toBe(true);
  });

  it('keeps the earlier copy of a skill it skips', async () => {
    await run({ providers: ['claude'] });
    mockExtract.mockResolvedValue(
      schema({
        skills: [
          { name: 'greeting', description: 'Greet users', tools: [] },
          { name: 'inline', description: 'Own', tools: [], hash: 'b2' },
        ],
      }),
    );

    expect(await run({ providers: ['claude'] })).toBe(1);
    expect(await fileExists(path.join(project, '.claude/skills/greeting/SKILL.md'))).toBe(true);
  });

  it('exports one skill by name, and leaves the other copies alone', async () => {
    expect(await run({ all: false, name: 'inline', providers: ['claude'], outDir: 'out' })).toBe(0);

    expect(await fileExists(path.join(project, 'out/.claude/skills/inline/SKILL.md'))).toBe(true);
    expect(await fileExists(path.join(project, 'out/.claude/skills/greeting'))).toBe(false);
  });

  it('keeps the copies of the other skills, and finds no drift in them, when --name comes with --all', async () => {
    await run({ providers: ['claude'] });

    expect(await run({ all: true, name: 'inline', providers: ['claude'] })).toBe(0);
    expect(await fileExists(path.join(project, '.claude/skills/greeting/SKILL.md'))).toBe(true);
    expect(await run({ all: true, name: 'inline', check: true, providers: ['claude'] })).toBe(0);
  });

  it('skips a skill whose content could not be loaded or whose name is not a folder name, and exits 1', async () => {
    mockExtract.mockResolvedValue(
      schema({
        skills: [
          { name: 'greeting', description: 'Greet users', tools: [] },
          { name: '../escape', description: 'Bad name', tools: [], hash: 'd4' },
        ],
      }),
    );

    expect(await run({ providers: ['claude'] })).toBe(1);
    expect(errors()).toContain('Skipped greeting: its instructions could not be loaded');
    expect(errors()).toContain('Invalid plugin name "../escape"');
  });

  it('refuses to export a skill into the folder that holds its own source, and leaves the source alone', async () => {
    const sourceDir = path.join(project, '.claude/skills/greeting');
    await ensureDir(path.join(sourceDir, 'references'));
    await writeFile(path.join(sourceDir, 'SKILL.md'), '## Greeting\n\nSay hello.\n');
    await writeFile(path.join(sourceDir, 'references', 'tone.md'), 'Be kind.');
    const own = schema();
    own.skillAssets[0] = {
      skillName: 'greeting',
      instructionFile: path.join(sourceDir, 'SKILL.md'),
      resourceDirs: { references: path.join(sourceDir, 'references') },
    };
    mockExtract.mockResolvedValue(own);

    expect(await run({ providers: ['claude'] })).toBe(1);
    expect(errors()).toContain(
      `Skipped greeting: ${path.join('.claude', 'skills', 'greeting')} holds the skill's own source`,
    );
    expect(await readFile(path.join(sourceDir, 'SKILL.md'))).toBe('## Greeting\n\nSay hello.\n');
    expect(await readFile(path.join(sourceDir, 'references', 'tone.md'))).toBe('Be kind.');
    expect(await fileExists(path.join(project, '.claude/skills/inline/SKILL.md'))).toBe(true);
  });

  it('leaves a folder of the same name that it did not write, and exits 1', async () => {
    await ensureDir(path.join(project, '.claude/skills/greeting'));
    await writeFile(path.join(project, '.claude/skills/greeting/SKILL.md'), 'written by hand');

    expect(await run({ providers: ['claude'] })).toBe(1);
    expect(errors()).toContain(
      `Skipped greeting: ${path.join('.claude', 'skills', 'greeting')} was not written by frontmcp skills export`,
    );
    expect(await readFile(path.join(project, '.claude/skills/greeting/SKILL.md'))).toBe('written by hand');
  });

  it('writes LF line endings, and passes --check on a copy checked out with CRLF', async () => {
    await writeFile(path.join(project, 'src', 'greeting.md'), '## Greeting\r\n\r\nSay hello.\r\n');
    await run({ providers: ['claude'] });
    const skillMdPath = path.join(project, '.claude/skills/greeting/SKILL.md');
    expect(await readFile(skillMdPath)).not.toContain('\r');

    await writeFile(skillMdPath, (await readFile(skillMdPath)).replace(/\n/g, '\r\n'));
    expect(await run({ check: true, providers: ['claude'] })).toBe(0);
  });

  it('copies a link inside a resource folder as a file, leaves out one that leads out of it, and passes --check', async () => {
    await writeFile(path.join(project, 'secret.txt'), 'not for agents');
    symlinkSync(path.join('..', '..', 'secret.txt'), path.join(project, 'src', 'refs', 'secret.md'));
    symlinkSync('tone.md', path.join(project, 'src', 'refs', 'tone-again.md'));
    symlinkSync('.', path.join(project, 'src', 'refs', 'loop'));

    expect(await run({ providers: ['claude'] })).toBe(0);
    const references = path.join(project, '.claude/skills/greeting/references');
    expect(await fileExists(path.join(references, 'secret.md'))).toBe(false);
    expect((await lstat(path.join(references, 'tone-again.md'))).isSymbolicLink()).toBe(false);
    expect(await readFile(path.join(references, 'tone-again.md'))).toBe('Be kind.');
    expect((console.log as jest.Mock).mock.calls.map((call) => String(call[0])).join('\n')).toContain(
      'left out references/secret.md of greeting: it links outside the skill',
    );
    expect(await run({ check: true, providers: ['claude'] })).toBe(0);
  });

  it('reports a broken link in a copy as drift instead of failing', async () => {
    await run({ providers: ['claude'] });
    symlinkSync(path.join(project, 'gone.md'), path.join(project, '.claude/skills/greeting/references/gone.md'));

    expect(await run({ check: true, providers: ['claude'] })).toBe(1);
    expect(errors()).toContain('modified: references/gone.md is not in the source');
  });

  it('keeps the copies another entry exported to the same folder', async () => {
    for (const app of ['a', 'b']) {
      await ensureDir(path.join(project, 'apps', app, 'src'));
      await writeFile(path.join(project, 'apps', app, 'src', 'main.ts'), 'export default {};');
    }
    jest.spyOn(process, 'cwd').mockReturnValue(path.join(project, 'apps', 'a'));
    mockExtract.mockResolvedValue(
      schema({ skills: [{ name: 'greeting', description: 'Greet', tools: [], hash: 'a1' }] }),
    );
    expect(await run({ providers: ['claude'], outDir: '../..' })).toBe(0);

    jest.spyOn(process, 'cwd').mockReturnValue(path.join(project, 'apps', 'b'));
    mockExtract.mockResolvedValue(schema({ skills: [{ name: 'inline', description: 'Own', tools: [], hash: 'b2' }] }));
    expect(await run({ providers: ['claude'], outDir: '../..' })).toBe(0);

    expect(await readFile(path.join(project, '.claude/skills/greeting/SKILL.md'))).toContain(
      'generated by frontmcp skills export from apps/a/src/main.ts',
    );
    expect(await fileExists(path.join(project, '.claude/skills/inline/SKILL.md'))).toBe(true);
  });

  it('refuses no selection, an unknown skill, no skills, and an entry without a manifest', async () => {
    await expect(run({ all: false })).rejects.toThrow('process.exit(1)');
    await expect(run({ all: false, name: 'nope' })).rejects.toThrow('process.exit(1)');
    expect(errors()).toContain('Skill "nope" not found in src/main.ts.');

    mockExtract.mockResolvedValue(schema({ skills: [] }));
    await expect(run()).rejects.toThrow('process.exit(1)');
    expect(errors()).toContain('No @Skill entries found in src/main.ts.');

    mockExtract.mockResolvedValue({ ...schema(), manifest: undefined, manifestError: 'old SDK' });
    await expect(run()).rejects.toThrow('process.exit(1)');
    expect(errors()).toContain('Could not build the manifest of src/main.ts: old SDK');

    mockExtract.mockRejectedValue(new Error('boot failed'));
    await expect(run()).rejects.toThrow('process.exit(1)');
    expect(errors()).toContain('Could not enumerate @Skill entries from src/main.ts: boot failed');
  });
});
