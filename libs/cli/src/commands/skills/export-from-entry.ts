// `frontmcp skills export --from-entry <entry> --provider claude,codex [--check]`: write a server's own `@Skill`
// entries to each agent's skills folder from one source, or report the copies that drifted from it.

import * as path from 'path';

import {
  copyFile,
  ensureDir,
  fileExists,
  readdir,
  readFile,
  readFileBuffer,
  realpath,
  rm,
  stat,
  writeFile,
} from '@frontmcp/utils';

import { c } from '../../core/colors';
import { resolveEntry } from '../../shared/fs';
import { assertValidPluginName } from '../build/exec/cli-runtime/plugin-emitter';
import type { ExtractedManifest, ExtractedSkillAsset } from '../build/exec/cli-runtime/schema-extractor';
import { composeSkillMd, readSkillInstructions } from '../build/exec/cli-runtime/skill-md-compose';
import { extractProjectSchema } from './from-entry';
import { PROVIDER_DIRS } from './install';

export type SkillProvider = keyof typeof PROVIDER_DIRS;

export interface ExportFromEntryOptions {
  /** The `--from-entry` path; the project's default entry when empty. */
  entry?: string;
  providers: SkillProvider[];
  name?: string;
  all?: boolean;
  /** The folder that gets each provider's skills folder (default: cwd). */
  outDir?: string;
  /** Write nothing; exit 1 when a copy differs from what export writes. */
  check?: boolean;
}

type ManifestSkill = ExtractedManifest['skills'][number];

interface SkillCopy {
  name: string;
  hash: string;
  skillMd: string;
  /** The instruction file and resource folders the copy is made from, which an export never replaces. */
  sources: string[];
  /** Each resource file by its path in the copy (`references/tone.md`), with the real path it is read from. */
  files: Map<string, string>;
  /** Resource paths left out: links that lead outside their folder, or nowhere. */
  leftOut: string[];
}

const RESOURCE_KINDS = ['references', 'examples', 'scripts', 'assets'] as const;
const MARKER_PATTERN = /^<!-- generated by frontmcp skills export from (.+?) \(source hash ([0-9a-f]+)\)/m;

function markerLine(source: string, hash: string): string {
  return `<!-- generated by frontmcp skills export from ${source} (source hash ${hash}); edit the source and export again -->`;
}

function readMarker(skillMd: string): { source: string; hash: string } | undefined {
  const match = MARKER_PATTERN.exec(skillMd);
  return match ? { source: match[1], hash: match[2] } : undefined;
}

const withLf = (text: string) => text.replace(/\r\n/g, '\n');

/** True for `parent` itself and any path inside it. */
function isWithin(child: string, parent: string): boolean {
  const relative = path.relative(parent, child);
  return relative === '' || (relative !== '..' && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative));
}

/** Files under `root` with their real paths, following links that stay inside it; the others are in `outside`. */
async function filesUnder(root: string): Promise<{ files: Array<{ name: string; real: string }>; outside: string[] }> {
  const realRoot = await realpath(root);
  const files: Array<{ name: string; real: string }> = [];
  const outside: string[] = [];
  const walk = async (dir: string, realDir: string, prefix: string, ancestors: ReadonlySet<string>): Promise<void> => {
    const within = new Set(ancestors).add(realDir);
    for (const name of (await readdir(dir)).sort()) {
      const full = path.join(dir, name);
      const real = await realpath(full).catch(() => undefined);
      if (!real || !isWithin(real, realRoot)) outside.push(`${prefix}${name}`);
      else if (!(await stat(real)).isDirectory()) files.push({ name: `${prefix}${name}`, real });
      else if (!within.has(real)) await walk(full, real, `${prefix}${name}/`, within);
    }
  };
  await walk(root, realRoot, '', new Set());
  return { files, outside };
}

/** Put the marker on the line after the frontmatter, where agents skip it and people see it first. */
function withMarker(skillMd: string, marker: string): string {
  const frontmatterEnd = skillMd.indexOf('\n---', 3);
  const lineEnd = skillMd.indexOf('\n', frontmatterEnd + 4);
  if (frontmatterEnd === -1 || lineEnd === -1) return `${skillMd}\n${marker}\n`;
  return `${skillMd.slice(0, lineEnd + 1)}${marker}\n\n${skillMd.slice(lineEnd + 1).replace(/^\n+/, '')}`;
}

/** The skill's tools, each with its purpose in the skill or the tool's own description. */
function toolsSection(skill: ManifestSkill, manifest: ExtractedManifest): string {
  if (skill.tools.length === 0) return '';
  const descriptions = new Map(manifest.tools.map((tool) => [tool.name, tool.description]));
  const lines = skill.tools.map((tool) => {
    const about = (tool.purpose ?? descriptions.get(tool.name) ?? '').split('\n')[0].trim();
    return about ? `- \`${tool.name}\`: ${about}` : `- \`${tool.name}\``;
  });
  return `\n\n## Tools\n\n${lines.join('\n')}`;
}

async function renderCopy(
  skill: ManifestSkill,
  asset: ExtractedSkillAsset | undefined,
  manifest: ExtractedManifest,
  source: string,
): Promise<SkillCopy | { skipReason: string }> {
  if (!skill.hash || !asset) return { skipReason: 'its instructions could not be loaded' };
  const instructions = await readSkillInstructions(asset);
  if ('skipReason' in instructions) return instructions;
  const composed = composeSkillMd(
    { name: skill.name, description: skill.description, tags: skill.tags, license: skill.license },
    withLf(instructions.body),
  );
  const sources: string[] = [];
  if (asset.instructionFile && (await fileExists(asset.instructionFile))) sources.push(asset.instructionFile);
  const files = new Map<string, string>();
  const leftOut: string[] = [];
  for (const kind of RESOURCE_KINDS) {
    const dir = asset.resourceDirs?.[kind];
    if (!dir || !(await fileExists(dir))) continue;
    sources.push(dir);
    const listed = await filesUnder(dir);
    for (const file of listed.files) files.set(`${kind}/${file.name}`, file.real);
    leftOut.push(...listed.outside.map((name) => `${kind}/${name}`));
  }
  return {
    name: skill.name,
    hash: skill.hash,
    skillMd: `${withMarker(composed.trimEnd() + toolsSection(skill, manifest), markerLine(source, skill.hash))}\n`,
    sources,
    files,
    leftOut,
  };
}

/** Why `targetDir` may not be written: it holds the skill's source, or (unless checking) it is not an export. */
async function refusalOf(copy: SkillCopy, targetDir: string, check: boolean): Promise<string | undefined> {
  const realTarget = await realpath(targetDir).catch(() => undefined);
  if (!realTarget) return undefined;
  for (const source of copy.sources) {
    const realSource = await realpath(source);
    if (isWithin(realSource, realTarget) || isWithin(realTarget, realSource)) {
      return "holds the skill's own source; export it to another folder with --out";
    }
  }
  if (check) return undefined;
  const skillMdPath = path.join(targetDir, 'SKILL.md');
  if ((await fileExists(skillMdPath)) && readMarker(await readFile(skillMdPath))) return undefined;
  return 'was not written by frontmcp skills export; move it away to export the skill there';
}

/** Why the copy in `targetDir` differs from what export writes, or undefined when it is the same. */
async function driftOf(copy: SkillCopy, targetDir: string): Promise<string | undefined> {
  const skillMdPath = path.join(targetDir, 'SKILL.md');
  if (!(await fileExists(skillMdPath))) return 'missing';
  const recorded = readMarker(await readFile(skillMdPath));
  if (!recorded) return 'not written by frontmcp skills export';
  if (recorded.hash !== copy.hash) return 'stale: the skill changed in the source since this copy was exported';
  const actual = await filesUnder(targetDir);
  if (actual.outside.length > 0) return `modified: ${actual.outside[0]} is not in the source`;
  for (const file of actual.files) {
    if (file.name === 'SKILL.md') {
      if (withLf(await readFile(file.real)) !== copy.skillMd) return 'modified: SKILL.md differs from the source';
      continue;
    }
    const source = copy.files.get(file.name);
    if (!source) return `modified: ${file.name} is not in the source`;
    if (!(await readFileBuffer(source)).equals(await readFileBuffer(file.real))) {
      return `modified: ${file.name} differs from the source`;
    }
  }
  const copied = new Set(actual.files.map((file) => file.name));
  const missing = [...copy.files.keys()].find((name) => !copied.has(name));
  return missing ? `modified: ${missing} is missing` : undefined;
}

async function writeCopy(copy: SkillCopy, targetDir: string): Promise<void> {
  await rm(targetDir, { recursive: true, force: true });
  await ensureDir(targetDir);
  await writeFile(path.join(targetDir, 'SKILL.md'), copy.skillMd);
  for (const [name, source] of copy.files) {
    const target = path.join(targetDir, ...name.split('/'));
    await ensureDir(path.dirname(target));
    await copyFile(source, target);
  }
}

/** The skill folders an export from `source` wrote that no longer match one of its skills. */
async function orphansOf(base: string, source: string, kept: ReadonlySet<string>): Promise<string[]> {
  if (!(await fileExists(base))) return [];
  const orphans: string[] = [];
  for (const name of (await readdir(base)).sort()) {
    const skillMdPath = path.join(base, name, 'SKILL.md');
    if (kept.has(name) || !(await fileExists(skillMdPath))) continue;
    if (readMarker(await readFile(skillMdPath))?.source === source) orphans.push(path.join(base, name));
  }
  return orphans;
}

export async function exportSkillsFromEntry(options: ExportFromEntryOptions): Promise<void> {
  if (!options.name && !options.all) {
    console.error(c('red', 'Specify a skill name or pass --all to export every skill of the entry.'));
    process.exit(1);
  }
  const cwd = process.cwd();
  const outDir = path.resolve(cwd, options.outDir ?? '.');
  const entry = await resolveEntry(cwd, options.entry);
  const source = path.relative(cwd, entry).split(path.sep).join('/');
  // Relative to the export folder, so two entries exporting to one folder never take each other's copies for orphans
  const markerSource = path.relative(outDir, entry).split(path.sep).join('/');

  let schema: Awaited<ReturnType<typeof extractProjectSchema>>;
  try {
    schema = await extractProjectSchema({ entry, cwd });
  } catch (err) {
    console.error(c('red', `Could not enumerate @Skill entries from ${source}: ${(err as Error).message}`));
    process.exit(1);
  }
  const manifest = schema.manifest;
  if (!manifest) {
    console.error(c('red', `Could not build the manifest of ${source}: ${schema.manifestError ?? 'unknown reason'}`));
    process.exit(1);
  }

  let skills = manifest.skills;
  if (options.name) {
    skills = skills.filter((skill) => skill.name === options.name);
    if (skills.length === 0) {
      console.error(c('red', `Skill "${options.name}" not found in ${source}.`));
      console.log(c('gray', `  Available: ${manifest.skills.map((skill) => skill.name).join(', ')}`));
      process.exit(1);
    }
  } else if (skills.length === 0) {
    console.error(c('red', `No @Skill entries found in ${source}.`));
    process.exit(1);
  }

  const assets = new Map(schema.skillAssets.map((asset) => [asset.skillName, asset]));
  const copies: SkillCopy[] = [];
  let skipped = 0;
  for (const skill of skills) {
    try {
      assertValidPluginName(skill.name, 'skills export --from-entry');
    } catch (err) {
      console.error(c('red', `  Skipped: ${(err as Error).message}`));
      skipped++;
      continue;
    }
    const copy = await renderCopy(skill, assets.get(skill.name), manifest, markerSource);
    if ('skipReason' in copy) {
      console.error(c('red', `  Skipped ${skill.name}: ${copy.skipReason}`));
      skipped++;
      continue;
    }
    if (!options.check) {
      for (const file of copy.leftOut) {
        console.log(c('yellow', `  left out ${file} of ${copy.name}: it links outside the skill, or to nothing`));
      }
    }
    copies.push(copy);
  }

  // A skill skipped above is still in the source: its earlier copy stays
  const kept = new Set(skills.map((skill) => skill.name));
  const drift: string[] = [];
  for (const provider of options.providers) {
    const base = path.join(outDir, PROVIDER_DIRS[provider]);
    for (const copy of copies) {
      const targetDir = path.join(base, copy.name);
      const label = path.relative(cwd, targetDir);
      const refusal = await refusalOf(copy, targetDir, options.check === true);
      if (refusal) {
        console.error(c('red', `  Skipped ${copy.name}: ${label} ${refusal}`));
        skipped++;
        continue;
      }
      if (options.check) {
        const reason = await driftOf(copy, targetDir);
        if (reason) drift.push(`${label}: ${reason}`);
      } else {
        await writeCopy(copy, targetDir);
        console.log(c('green', `wrote ${label}`));
      }
    }
    if (!options.all) continue;
    for (const orphan of await orphansOf(base, markerSource, kept)) {
      const label = path.relative(cwd, orphan);
      if (options.check) {
        drift.push(`${label}: removed from the source`);
      } else {
        await rm(orphan, { recursive: true, force: true });
        console.log(c('yellow', `removed ${label} (no longer in ${source})`));
      }
    }
  }

  if (skipped > 0) process.exitCode = 1;
  const providers = options.providers.join(', ');
  if (!options.check) {
    console.log(c('bold', `\n${copies.length} skill(s) exported from ${source} to ${providers}.\n`));
    return;
  }
  if (drift.length === 0) {
    console.log(c('green', `${copies.length} skill(s) in ${providers} match ${source}.`));
    return;
  }
  for (const line of drift) console.error(c('red', `drift: ${line}`));
  console.error(
    c(
      'red',
      `\n${drift.length} skill ${drift.length === 1 ? 'copy' : 'copies'} drifted from ${source}. Run the export without --check to update them.`,
    ),
  );
  process.exitCode = 1;
}
