import {
  bundleSkillFiles,
  composeBundleSkillMd,
  readBundleSkills,
  shellCommandLine,
  type BundleSkill,
  type BundleSkillCommands,
} from '../bundle-skills';
import type { SkilledClient } from '../skilled-commands';

const ALL_TOOLS = ['search_skill', 'load_skill', 'execute_action', 'run_workflow'];

const commands: BundleSkillCommands = {
  bin: 'mymcp',
  cli: 'mymcp',
  toolNames: ALL_TOOLS,
  topLevel: true,
  refresh: 'mymcp install -p claude --refresh-skills',
};

const refunds: BundleSkill = {
  id: 'refunds',
  name: 'Guarded action',
  description: 'Refund an invoice: check it first.',
  instructions: '# Refunds\n\nCheck the invoice before refunding it.\n',
  bundleVersion: '1.4.0',
  actions: [
    {
      actionId: 'getInvoice',
      summary: 'Get an invoice by id.',
      inputJsonSchema: {
        type: 'object',
        properties: { id: { type: 'string', examples: ['inv_1'] }, expand: { type: 'boolean' } },
        required: ['id'],
      },
    },
    {
      actionId: 'refundInvoice',
      summary: 'Refund an invoice.',
      description: 'Refunds part or all of a paid invoice.',
      inputJsonSchema: {
        type: 'object',
        properties: { id: { type: 'string' }, amount: { type: 'integer' } },
        required: ['id', 'amount'],
      },
    },
  ],
};

describe('composeBundleSkillMd', () => {
  const skillMd = composeBundleSkillMd(refunds, commands);

  it('keeps the display name and description in the frontmatter, marked as generated from the bundle version', () => {
    expect(skillMd.startsWith(
      [
        '---',
        'name: Guarded action',
        'description: "Refund an invoice: check it first."',
        'metadata:',
        '  source: "skilled-openapi-bundle"',
        '  bundle-version: "1.4.0"',
        '  generated-by: "mymcp install"',
        '---',
        '',
      ].join('\n'),
    )).toBe(true);
  });

  it('says which bundle version it was generated for and how to refresh it, then gives the instructions', () => {
    expect(skillMd).toContain(
      "> Generated by `mymcp install` from version 1.4.0 of the server's skill bundle. Don't edit it: after the " +
        'bundle changes, run `mymcp install -p claude --refresh-skills` to write it again.\n\n# Refunds\n\n' +
        'Check the invoice before refunding it.\n\n## Actions',
    );
  });

  it('lists each action with its summary and a ready execute command built from its input schema', () => {
    expect(skillMd).toContain(
      [
        '### getInvoice',
        '',
        'Get an invoice by id.',
        '',
        '```bash',
        `mymcp execute getInvoice --input '{"id":"inv_1"}'`,
        '```',
        '',
        'Optional input: `expand`.',
      ].join('\n'),
    );
    expect(skillMd).toContain(
      [
        '### refundInvoice',
        '',
        'Refund an invoice.',
        '',
        'Refunds part or all of a paid invoice.',
        '',
        '```bash',
        `mymcp execute refundInvoice --input '{"id":"<id>","amount":0}'`,
        '```',
      ].join('\n'),
    );
  });

  it('tells the agent how a confirmation is given', () => {
    expect(skillMd).toContain('ask the user, then run the command again with `--yes`');
  });

  it('shows how to chain several actions with run_workflow', () => {
    expect(skillMd).toContain('## Several actions at once');
    expect(skillMd).toContain(
      `\`\`\`bash\nmymcp run_workflow 'return await callTool("getInvoice", {"id":"inv_1"});'\n\`\`\`\n`,
    );
  });

  it('names the skills group commands on a server with tools of its own', () => {
    const grouped = composeBundleSkillMd(refunds, { ...commands, topLevel: false });

    expect(grouped).toContain(`mymcp skills execute getInvoice --input '{"id":"inv_1"}'`);
    expect(grouped).toContain('mymcp skills run \'return await callTool(');
  });

  it('leaves out the commands of the tools the CLI has none for', () => {
    const workflowOnly = composeBundleSkillMd(refunds, { ...commands, toolNames: ['search_skill', 'load_skill', 'run_workflow'] });
    const executeOnly = composeBundleSkillMd(refunds, { ...commands, toolNames: ['search_skill', 'load_skill', 'execute_action'] });

    expect(workflowOnly).not.toContain('mymcp execute');
    expect(workflowOnly).toContain('Run these actions in a workflow, below.');
    expect(executeOnly).not.toContain('run_workflow');
  });

  it('says so for a skill with no action the caller may run', () => {
    const noActions = composeBundleSkillMd({ ...refunds, actions: [] }, commands);

    expect(noActions).toContain('## Actions\n\nThis skill has no actions you may run.\n');
    expect(noActions).not.toContain('## Several actions at once');
  });
});

describe('bundleSkillFiles', () => {
  it('composes each skill and reports the bundle version', () => {
    expect(bundleSkillFiles([refunds], commands)).toEqual({
      bundleVersion: '1.4.0',
      skills: [{ id: 'refunds', name: 'Guarded action', skillMd: composeBundleSkillMd(refunds, commands) }],
    });
    expect(bundleSkillFiles([], commands)).toEqual({ bundleVersion: undefined, skills: [] });
  });
});

describe('readBundleSkills', () => {
  function clientServing(options: {
    index: Array<{ type: string; name?: string }>;
    skills: Record<string, Record<string, unknown>>;
    searchError?: string;
  }): SkilledClient & { loads: string[][] } {
    const loads: string[][] = [];
    return {
      loads,
      readResource: async () => ({ contents: [{ text: JSON.stringify({ skills: options.index }) }] }),
      callTool: async (name, args) => {
        if (name === 'search_skill') {
          return options.searchError
            ? { isError: true, content: [{ type: 'text', text: options.searchError }] }
            : { structuredContent: { skills: [] } };
        }
        const skillIds = args['skillIds'] as string[];
        loads.push(skillIds);
        const missing = skillIds.find((id) => !options.skills[id]);
        if (missing) return { isError: true, content: [{ type: 'text', text: `Skill "${missing}" not found` }] };
        return { structuredContent: { skills: skillIds.map((id) => ({ skill: options.skills[id], isComplete: true })) } };
      },
    };
  }

  it("loads the caller's skills from the index and keeps the bundle's, sorted by id", async () => {
    const client = clientServing({
      index: [
        { type: 'skill-md', name: 'Invoices' },
        { type: 'skill-md', name: 'math-helper' },
        { type: 'mcp-resource-template' },
        { type: 'skill-md', name: 'Guarded action' },
      ],
      skills: {
        Invoices: { id: 'invoices', name: 'Invoices', description: 'd', instructions: 'i', bundleVersion: '2.0.0' },
        'math-helper': { id: 'math-helper', name: 'math-helper', description: 'd', instructions: 'i' },
        'Guarded action': {
          id: 'guarded',
          name: 'Guarded action',
          description: 'd',
          instructions: 'i',
          bundleVersion: '2.0.0',
          actions: refunds.actions,
        },
      },
    });

    const skills = await readBundleSkills(client);

    expect(skills.map((skill) => [skill.id, skill.actions.length])).toEqual([
      ['guarded', 2],
      ['invoices', 0],
    ]);
    expect(client.loads).toEqual([['Invoices', 'math-helper', 'Guarded action']]);
  });

  it('loads ten skills per load_skill call', async () => {
    const names = Array.from({ length: 12 }, (_, position) => `skill-${position}`);
    const client = clientServing({
      index: names.map((name) => ({ type: 'skill-md', name })),
      skills: Object.fromEntries(
        names.map((name) => [name, { id: name, name, description: 'd', instructions: 'i', bundleVersion: '1' }]),
      ),
    });

    expect(await readBundleSkills(client)).toHaveLength(12);
    expect(client.loads.map((batch) => batch.length)).toEqual([10, 2]);
  });

  it('fails when the server has no bundle loaded, rather than reading no skills', async () => {
    const client = clientServing({
      index: [],
      skills: {},
      searchError: 'No skill bundle is loaded: bundle acme:billing@1.4.0 was not applied',
    });

    await expect(readBundleSkills(client)).rejects.toThrow('No skill bundle is loaded');
  });

  it('fails when a skill the index lists does not load', async () => {
    const client = clientServing({ index: [{ type: 'skill-md', name: 'Invoices' }], skills: {} });

    await expect(readBundleSkills(client)).rejects.toThrow('Skill "Invoices" not found');
  });
});

describe('shellCommandLine', () => {
  it('quotes only the words a shell would split or expand', () => {
    expect(shellCommandLine(['/usr/local/bin/node', '/opt/my app/mymcp-cli.bundle.js', "it's"])).toBe(
      `/usr/local/bin/node '/opt/my app/mymcp-cli.bundle.js' 'it'\\''s'`,
    );
  });
});
