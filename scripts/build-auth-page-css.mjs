// Builds the stylesheet the built-in auth pages inline (libs/auth/src/ui/auth-page-styles.ts) from the Tailwind classes their source uses; --check only reports a stale file.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { transformSync } from 'esbuild';
import prettier from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { compile } = require('tailwindcss');

const UI_DIR = path.join(root, 'libs/auth/src/ui');
const SOURCES = ['templates.ts', 'base-layout.ts'];
export const OUTPUT = path.join(UI_DIR, 'auth-page-styles.ts');

/** The DEFAULT_THEME colors in base-layout.ts, as `[name, value]` pairs. */
function defaultThemeColors(baseLayout) {
  const block = baseLayout.match(/DEFAULT_THEME[^=]*=\s*\{\s*colors:\s*\{([^}]*)\}/)?.[1];
  if (!block) throw new Error('DEFAULT_THEME.colors not found in base-layout.ts');
  return [...block.matchAll(/'?([\w-]+)'?:\s*'([^']+)'/g)].map((match) => [match[1], match[2]]);
}

/** Every word of the sources that could be a class name; Tailwind ignores the ones that aren't. */
function candidates(sources) {
  return [
    ...new Set(
      sources
        .join('\n')
        .split(/[\s"'`<>{}()=;,$]+/)
        .filter(Boolean),
    ),
  ];
}

async function stylesheet() {
  const sources = SOURCES.map((file) => readFileSync(path.join(UI_DIR, file), 'utf8'));
  // `reference`: the utilities fall back to these values, and a page's theme can still set the variables.
  const theme = defaultThemeColors(sources[1])
    .map(([name, value]) => `--color-${name}: ${value};`)
    .join(' ');
  const tailwindDir = path.dirname(require.resolve('tailwindcss/package.json'));
  const compiler = await compile(`@import "tailwindcss";\n@theme reference { ${theme} }`, {
    base: root,
    loadStylesheet: async (id, base) => {
      const file = id === 'tailwindcss' ? path.join(tailwindDir, 'index.css') : path.resolve(base, id);
      return { path: file, base: path.dirname(file), content: readFileSync(file, 'utf8') };
    },
  });
  const css = compiler.build(candidates(sources));
  return transformSync(css, { loader: 'css', minify: true, legalComments: 'inline' }).code.trim();
}

export async function authPageStylesModule() {
  const source = `// Generated by scripts/build-auth-page-css.mjs from the classes in templates.ts and base-layout.ts. Run \`node scripts/build-auth-page-css.mjs\` after changing them.

/** The built-in auth pages' stylesheet: the Tailwind utilities their classes use, Tailwind's preflight and a system font stack. */
export const AUTH_PAGE_CSS = ${JSON.stringify(await stylesheet())};
`;
  const options = await prettier.resolveConfig(OUTPUT);
  return prettier.format(source, { ...options, filepath: OUTPUT });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const generated = await authPageStylesModule();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUTPUT, 'utf8') !== generated) {
      console.error(`${path.relative(root, OUTPUT)} is stale; run node scripts/build-auth-page-css.mjs`);
      process.exit(1);
    }
    console.log(`build-auth-page-css: ${path.relative(root, OUTPUT)} is current.`);
  } else {
    writeFileSync(OUTPUT, generated);
    console.log(`build-auth-page-css: wrote ${path.relative(root, OUTPUT)}.`);
  }
}
